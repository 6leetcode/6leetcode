class Testing {
  public static void main(String[] args) {
    int[] nums = new int[] { 1, 2, 3, 4, 5 };
    int input2 = 2;
    ListNode head = intsToList(nums);
    System.out.println("Input:  " + listToInts(head) + " " + input2);
    ListNode res = new Solution().removeNthFromEnd(head, input2);
    System.out.println("Output: " + listToInts(res));
  }

  public static ListNode intsToList(int[] nums) {
    ListNode dummy = new ListNode(0);
    ListNode cur = dummy;
    for (int n : nums) {
      cur.next = new ListNode(n);
      cur = cur.next;
    }
    return dummy.next;
  }

  public static String listToInts(ListNode head) {
    StringBuilder sb = new StringBuilder("[");
    boolean first = true;
    while (head != null) {
      sb.append(first ? "" : ", ").append(head.val);
      first = false;
      head = head.next;
    }
    return sb.append("]").toString();
  }
}
